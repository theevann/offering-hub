const { createLogger } = require("../src/utils/logger");
const log = createLogger("rebuild-initial-migration");

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const apiRoot = path.resolve(__dirname, "..");
const prismaRoot = path.join(apiRoot, "prisma");
const migrationsRoot = path.join(prismaRoot, "migrations");
const defaultInitialMigration = "0_init";

function rebuildInitialMigration() {
  const folders = (fs.existsSync(migrationsRoot)
    ? fs.readdirSync(migrationsRoot, { withFileTypes: true })
    : [])
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name);

  if (folders.length > 1 || (folders.length === 1 &&
    ![defaultInitialMigration].includes(folders[0]))) {
    throw new Error("Expected no migrations or only the initial migration (0_init or 20260307073525_init). Use incremental migrations once additional migrations exist.");
  }

  // Preserve an existing migration's identity; fresh databases use the shorter name.
  const initialMigration = defaultInitialMigration;

  const extensions = fs.readFileSync(path.join(prismaRoot, "sql/extensions.sql"), "utf8");
  const spatial = fs.readFileSync(path.join(prismaRoot, "sql/spatial.sql"), "utf8");
  const target = path.join(migrationsRoot, initialMigration, "migration.sql");
  const staged = `${target}.tmp`;
  const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "coie-migration-"));

  try {
    const prismaCli = path.join(apiRoot, "node_modules/prisma/build/index.js");
    const generatedFile = path.join(temporaryDirectory, "schema.sql");
    const runPrisma = args => execFileSync(process.execPath, [prismaCli, ...args], {
      cwd: apiRoot,
      stdio: "inherit"
    });

    runPrisma(["validate", "--schema", "prisma/schema.prisma"]);
    runPrisma([
      "migrate", "diff",
      "--from-empty",
      "--to-schema", "prisma/schema.prisma",
      "--script",
      "--output", generatedFile
    ]);

    const generated = fs.readFileSync(generatedFile, "utf8");
    if (!generated.trim()) throw new Error("Prisma generated empty SQL; leaving the migration unchanged.");

    const sql = [
      "-- Generated by npm run db:rebuild-migration.\n-- Edit prisma/schema.prisma and prisma/sql/*.sql instead.\n-- For recreating disposable development databases only.",
      extensions.trim(),
      generated.trim(),
      spatial.trim()
    ].join("\n\n") + "\n";

    // Replace the migration only after all generation steps have succeeded.
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const lockFile = path.join(migrationsRoot, "migration_lock.toml");
    if (!fs.existsSync(lockFile)) {
      fs.writeFileSync(lockFile, 'provider = "postgresql"\n', { flag: "wx" });
    }
    fs.writeFileSync(staged, sql);
    fs.renameSync(staged, target);
    log.info(`Rebuilt prisma/migrations/${initialMigration}/migration.sql`);
    log.info("No database was changed. Review the SQL before resetting a disposable development database.");
  } finally {
    fs.rmSync(temporaryDirectory, { recursive: true, force: true });
    fs.rmSync(staged, { force: true });
  }
}

try {
  rebuildInitialMigration();
} catch (error) {
  log.error(error.message);
  process.exitCode = 1;
}
